CREATE TABLE IF NOT EXISTS grp_progression (
    citizenid VARCHAR(50) NOT NULL,
    xp INT UNSIGNED NOT NULL DEFAULT 0,
    playtime INT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (citizenid)
);

CREATE TABLE IF NOT EXISTS grp_job_xp (
    citizenid VARCHAR(50) NOT NULL,

    law_xp INT UNSIGNED NOT NULL DEFAULT 0,
    taxi_xp INT UNSIGNED NOT NULL DEFAULT 0,
    medic_xp INT UNSIGNED NOT NULL DEFAULT 0,
    mechanic_xp INT UNSIGNED NOT NULL DEFAULT 0,
    trucking_xp INT UNSIGNED NOT NULL DEFAULT 0,
    civilian_xp INT UNSIGNED NOT NULL DEFAULT 0,

    updated_at TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (citizenid)
);
